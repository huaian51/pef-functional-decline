# Manuscript:
# Cumulative low peak expiratory flow burden and severity of subsequent
# functional decline: a four-cohort longitudinal study
#
# PURPOSE
# -------
# Provide an intuitive supportive representation of the primary cumulative
# burden finding using the number of low-PEF observations across two
# assessments:
#
#   0 low-PEF observations = reference
#   1 low-PEF observation
#   2 low-PEF observations
#
# MAIN PANELS
# -----------
# A. Any limitation vs Independent
# B. Severe limitation vs Independent
# C. Severe vs Mild
#
# Each panel shows pooled categorical ORs for 0 / 1 / 2 low-PEF observations,
# with the pooled linear trend per +1 low-PEF occasion annotated below.
#
# IMPORTANT
# ---------
# - This is a SUPPORTIVE exposure representation, not the primary exposure.
# - The 0 / 1 / 2 variable is the number of low-PEF observations across two
#   assessments. It must NOT be described as a trajectory.
# - The primary manuscript exposure remains the unified continuous cumulative low-PEF burden.
