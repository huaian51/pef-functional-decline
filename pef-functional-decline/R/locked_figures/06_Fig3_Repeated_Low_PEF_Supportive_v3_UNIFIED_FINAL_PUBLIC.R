fmt_num <- function(
  x,
  digits = 2
) {
  ifelse(
    is.na(x),
    "NA",
    formatC(
      x,
      format = "f",
      digits = digits
    )
  )
}

fmt_or_ci <- function(
  est,
  low,
  high,
  digits = 2
) {
  paste0(
    fmt_num(
      est,
      digits
    ),
    " (",
    fmt_num(
      low,
      digits
    ),
    "-",
    fmt_num(
      high,
      digits
    ),
    ")"
  )
}

fmt_p <- function(p) {
  ifelse(
    is.na(p),
    "",
    ifelse(
      p < 0.001,
      "P<0.001",
      paste0(
        "P=",
        formatC(
          p,
          format = "f",
          digits = 3
        )
      )
    )
  )
}


