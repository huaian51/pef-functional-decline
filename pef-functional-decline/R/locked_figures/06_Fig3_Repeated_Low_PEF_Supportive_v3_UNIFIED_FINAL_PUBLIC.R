EXPECTED <- data.table(
  estimand = c(
    "A_ANY_LIMITATION",
    "A_ANY_LIMITATION",
    "A_ANY_LIMITATION",
    "SEVERE_VS_INDEPENDENT",
    "SEVERE_VS_INDEPENDENT",
    "SEVERE_VS_INDEPENDENT",
    "SEVERE_VS_MILD",
    "SEVERE_VS_MILD",
    "SEVERE_VS_MILD"
  ),
  contrast = c(
    "1 vs 0",
    "2 vs 0",
    "per +1 low occasion",
    "1 vs 0",
    "2 vs 0",
    "per +1 low occasion",
    "1 vs 0",
    "2 vs 0",
    "per +1 low occasion"
  ),
  expected_OR = c(
    1.251900,
    1.542527,
    1.245733,
    1.488079,
    2.035399,
    1.441822,
    1.344283,
    1.562512,
    1.280396
  )
)

QC_TOL <- 5e-4

obs_qc <- M[
  estimand %in%
    PANEL_MAP$estimand &
  contrast %in%
    EXPECTED$contrast,
  .(
    estimand,
    contrast,
    observed_OR = pooled_OR
  )
]

QC <- merge(
  EXPECTED,
  obs_qc,
  by = c(
    "estimand",
    "contrast"
  ),
  all.x = TRUE
)

QC[
  ,
  abs_difference :=
    abs(
      observed_OR -
      expected_OR
    )
]

QC[
  ,
  pass :=
    abs_difference <=
      QC_TOL
]

cat("\n")
cat("======================================================================\n")
cat("FIGURE 3 INPUT QC\n")
cat("======================================================================\n")
print(QC)

if (!all(QC$pass)) {
  stop(
    "Figure 3 input results do not match the locked supportive analysis.",
    call. = FALSE
  )
}


# ==============================================================================
# 5. BUILD CATEGORICAL 0 / 1 / 2 DATA
# ==============================================================================

CAT <- M[
  estimand %in%
    PANEL_MAP$estimand &
  exposure_spec ==
    "CATEGORICAL_0_1_2" &
  contrast %in%
    c(
      "1 vs 0",
      "2 vs 0"
    ),
  .(
    estimand,
    contrast,
    OR = pooled_OR,
    CI_low = CI_low_mKH,
    CI_high = CI_high_mKH,
    P = P_mKH,
    I2
  )
]

# Add reference category explicitly.
REF <- unique(
  CAT[
    ,
    .(
      estimand
    )
  ]
)

REF[
  ,
  `:=`(
    contrast = "0 reference",
    OR = 1,
    CI_low = 1,
    CI_high = 1,
    P = NA_real_,
    I2 = NA_real_
  )
]

CAT <- rbindlist(
  list(
    REF,
    CAT
  ),
  fill = TRUE
)

CAT[
  ,
  low_count := fifelse(
    contrast ==
      "0 reference",
    0L,
    fifelse(
      contrast ==
        "1 vs 0",
      1L,
      2L
    )
  )
]

CAT <- merge(
  CAT,
  PANEL_MAP,
  by = "estimand",
  all.x = TRUE,
  sort = FALSE
)

CAT[
  ,
  panel := factor(
    paste0(
      panel_letter,
      "  ",
      panel_title
    ),
    levels = paste0(
      PANEL_MAP$panel_letter,
      "  ",
      PANEL_MAP$panel_title
    )
  )
]

CAT[
  ,
  point_label := fifelse(
    low_count ==
      0L,
    "Reference",
    fmt_or_ci(
      OR,
      CI_low,
      CI_high,
      digits = 2
    )
  )
]


