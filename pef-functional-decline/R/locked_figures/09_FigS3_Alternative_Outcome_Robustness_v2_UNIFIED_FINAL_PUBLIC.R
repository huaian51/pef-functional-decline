build_cohort_qc <- function(
  observed_dt,
  expected_dt
) {

  z <- merge(
    observed_dt[
      ,
      .(
        cohort,
        observed_OR = effect_std
      )
    ],
    expected_dt,
    by = "cohort",
    all.y = TRUE
  )

  z[
    ,
    abs_difference :=
      abs(
        observed_OR -
          expected_OR
      )
  ]

  z[
    ,
    pass :=
      !is.na(observed_OR) &
      abs_difference <= QC_TOL
  ]

  z[]
}

