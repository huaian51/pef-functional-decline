pick_col <- function(dt, candidates) {
  hit <- candidates[
    candidates %in% names(dt)
  ]

  if (length(hit) == 0L) {
    return(NULL)
  }

  hit[1]
}


standardize_cohort_results <- function(dt) {

  dt <- as.data.table(copy(dt))

  or_col <- pick_col(
    dt,
    c(
      "OR",
      "effect",
      "estimate"
    )
  )

  low_col <- pick_col(
    dt,
    c(
      "CI_low",
      "CI_low_95",
      "lower",
      "lower_CI"
    )
  )

  high_col <- pick_col(
    dt,
    c(
      "CI_high",
      "CI_high_95",
      "upper",
      "upper_CI"
    )
  )

  if (
    is.null(or_col) ||
    is.null(low_col) ||
    is.null(high_col)
  ) {
    stop(
      "Could not identify OR / CI columns in cohort-level result file.",
      call. = FALSE
    )
  }

  dt[
    ,
    `:=`(
      effect_std = as.numeric(
        get(or_col)
      ),
      low_std = as.numeric(
        get(low_col)
      ),
      high_std = as.numeric(
        get(high_col)
      )
    )
  ]

  dt
}


standardize_meta_results <- function(dt) {

  dt <- as.data.table(copy(dt))

  or_col <- pick_col(
    dt,
    c(
      "pooled_OR",
      "pooled_effect",
      "OR",
      "effect"
    )
  )

  low_col <- pick_col(
    dt,
    c(
      "CI_low_mKH",
      "CI_low",
      "lower",
      "lower_CI"
    )
  )

  high_col <- pick_col(
    dt,
    c(
      "CI_high_mKH",
      "CI_high",
      "upper",
      "upper_CI"
    )
  )

  i2_col <- pick_col(
    dt,
    c(
      "I2",
      "I2_pct",
      "I2_percent"
    )
  )

  if (
    is.null(or_col) ||
    is.null(low_col) ||
    is.null(high_col)
  ) {
    stop(
      "Could not identify pooled OR / CI columns in meta-analysis file.",
      call. = FALSE
    )
  }

  dt[
    ,
    `:=`(
      effect_std = as.numeric(
        get(or_col)
      ),
      low_std = as.numeric(
        get(low_col)
      ),
      high_std = as.numeric(
        get(high_col)
      ),
      I2_std = if (
        !is.null(i2_col)
      ) {
        as.numeric(
          get(i2_col)
        )
      } else {
        NA_real_
      }
    )
  ]

  dt
}


fmt_or_ci <- function(
  est,
  low,
  high
) {
  paste0(
    sprintf("%.2f", est),
    " (",
    sprintf("%.2f", low),
    "-",
    sprintf("%.2f", high),
    ")"
  )
}


fmt_i2 <- function(x) {
  ifelse(
    is.na(x),
    "",
    paste0(
      "I",
      intToUtf8(178),
      "=",
      sprintf("%.1f", x),
      "%"
    )
  )
}


